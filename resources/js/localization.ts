export function translate(locale: PublicLocale, key: Key): string {
    if (locale === 'sn') {
        return shona[key] ?? english[key];
    }
    if (locale === 'nd') {
        return ndebele[key] ?? english[key];
    }

    return english[key];
}

export function normalizeLocale(locale: unknown): PublicLocale {
    if (locale === 'sn' || locale === 'nd') {
        return locale;
    }

    return 'en';
}
